// Store chart instances so we can destroy & recreate them on each prediction
let distributionChart = null;
let spamKeywordsChart = null;
let hamKeywordsChart = null;

// Session prediction counters
let sessionHamCount = 0;
let sessionSpamCount = 0;

document.addEventListener("DOMContentLoaded", () => {
    // 1. Check if model data is loaded from src/model_data.js
    if (typeof MODEL_DATA === "undefined") {
        console.error("MODEL_DATA is undefined. Please make sure src/model_data.js is generated by running training.");
        alert("Warning: Model data not found! Please make sure you run 'python src/train.py' to generate the model parameters before using this system.");
        return;
    }

    // 2. Bind model name and static training metrics (collapsible section)
    const bestModelName = MODEL_DATA.best_model;
    const metrics = bestModelName === "Multinomial Naive Bayes" ? MODEL_DATA.nb_metrics : MODEL_DATA.lr_metrics;

    document.getElementById("champion-model-name").innerText = bestModelName;
    document.getElementById("metric-accuracy").innerText = (metrics.accuracy * 100).toFixed(2) + "%";
    document.getElementById("metric-precision").innerText = (metrics.precision_spam * 100).toFixed(2) + "%";
    document.getElementById("metric-recall").innerText = (metrics.recall_spam * 100).toFixed(2) + "%";
    document.getElementById("metric-f1").innerText = (metrics.f1_spam * 100).toFixed(2) + "%";

    // 3. Render initial placeholder charts (showing dataset-level data until first prediction)
    renderInitialCharts();

    // 5. Predict Event Listener
    const btn = document.getElementById("analyze-btn");
    const txtArea = document.getElementById("message-input");
    const resultCard = document.getElementById("result-card");
    const resultTitle = document.getElementById("result-title");
    const confidenceText = document.getElementById("confidence-percent");
    const progressBar = document.getElementById("progress-bar");

    btn.addEventListener("click", () => {
        const text = txtArea.value.trim();
        if (!text) {
            alert("Please enter a message to analyze.");
            return;
        }

        const prediction = runClientSideInference(text);

        // Update left-side result card
        resultCard.style.display = "block";
        if (prediction.label === "Spam") {
            resultCard.className = "result-card spam";
            resultTitle.innerHTML = "🚨 Warning: This message is classified as SPAM!";
        } else {
            resultCard.className = "result-card ham";
            resultTitle.innerHTML = "✅ Safe: This message is classified as HAM (Legitimate).";
        }

        const confPercent = (prediction.confidence * 100).toFixed(2) + "%";
        confidenceText.innerText = confPercent;
        progressBar.style.width = confPercent;

        // ---- Update RIGHT-SIDE dynamic metric cards ----
        const spamPct = (prediction.spamProb * 100).toFixed(2);
        const hamPct = ((1 - prediction.spamProb) * 100).toFixed(2);

        document.getElementById("metric-spam-prob").innerText = spamPct + "%";
        document.getElementById("metric-ham-prob").innerText = hamPct + "%";
        document.getElementById("metric-word-count").innerText = text.split(/\s+/).filter(w => w.length > 0).length;
        document.getElementById("metric-char-count").innerText = text.length;

        // Color-code the probability cards
        const spamCard = document.getElementById("card-spam-prob");
        const hamCard = document.getElementById("card-ham-prob");

        if (prediction.label === "Spam") {
            spamCard.style.background = "#fee2e2";
            spamCard.style.borderColor = "#fecaca";
            hamCard.style.background = "#f8fafc";
            hamCard.style.borderColor = "#f1f5f9";
        } else {
            hamCard.style.background = "#dcfce7";
            hamCard.style.borderColor = "#bbf7d0";
            spamCard.style.background = "#f8fafc";
            spamCard.style.borderColor = "#f1f5f9";
        }

        // Animate the probability needle
        const needle = document.getElementById("prob-needle");
        const probLabel = document.getElementById("prob-label");
        needle.style.left = (prediction.spamProb * 100) + "%";
        probLabel.innerText = prediction.label === "Spam"
            ? `Spam detected with ${spamPct}% probability`
            : `Ham (safe) with ${hamPct}% probability`;

        // Hide the hint text
        const hint = document.getElementById("analysis-hint");
        if (hint) hint.style.display = "none";

        // ---- Update SESSION PREDICTION TRACKER ----
        if (prediction.label === "Spam") {
            sessionSpamCount++;
        } else {
            sessionHamCount++;
        }
        const totalCount = sessionHamCount + sessionSpamCount;
        document.getElementById("cm-ham-count").innerText = sessionHamCount;
        document.getElementById("cm-spam-count").innerText = sessionSpamCount;
        document.getElementById("cm-total-count").innerText = totalCount;

        // Highlight the active prediction row
        const hamLabel = document.getElementById("cm-ham-label");
        const hamCountEl = document.getElementById("cm-ham-count");
        const spamLabel = document.getElementById("cm-spam-label");
        const spamCountEl = document.getElementById("cm-spam-count");

        if (prediction.label === "Spam") {
            spamLabel.style.background = "#fee2e2";
            spamCountEl.style.background = "#fee2e2";
            hamLabel.style.background = "";
            hamCountEl.style.background = "";
        } else {
            hamLabel.style.background = "#dcfce7";
            hamCountEl.style.background = "#dcfce7";
            spamLabel.style.background = "";
            spamCountEl.style.background = "";
        }

        // ---- Update ALL CHARTS dynamically for this message ----
        updateChartsForMessage(prediction);
    });
});

/**
 * Normalizes input text following the exact preprocessing rules in Python:
 * Convert to lowercase, strip digits/punctuation/symbols, collapse spaces.
 */
function cleanTextJS(text) {
    let cleaned = text.toLowerCase();
    cleaned = cleaned.replace(/[^a-zA-Z\s]/g, ' ');
    cleaned = cleaned.replace(/\s+/g, ' ').trim();
    return cleaned;
}

/**
 * Executes a serverless TF-IDF + Classifier prediction in client-side Javascript.
 * Returns label, confidence, spamProb, and per-word contribution scores.
 */
function runClientSideInference(message) {
    const cleaned = cleanTextJS(message);
    const tokens = cleaned.split(' ').filter(t => t.length > 0);
    
    if (tokens.length === 0) {
        return { label: "Ham", confidence: 1.0, spamProb: 0.0, wordContributions: [] };
    }

    // Count token occurrences
    const tokenCounts = {};
    tokens.forEach(t => {
        tokenCounts[t] = (tokenCounts[t] || 0) + 1;
    });

    // Compute unnormalized TF-IDF vector
    let sumOfSquares = 0;
    const tfidfVector = {};
    const wordToIdx = {};

    Object.keys(tokenCounts).forEach(word => {
        if (word in MODEL_DATA.vocabulary) {
            const idx = MODEL_DATA.vocabulary[word];
            const tf = tokenCounts[word] / tokens.length;
            const idf = MODEL_DATA.idf[idx];
            const tfidfVal = tf * idf;
            tfidfVector[idx] = tfidfVal;
            wordToIdx[word] = idx;
            sumOfSquares += tfidfVal * tfidfVal;
        }
    });

    // Apply L2 Normalization
    const l2Norm = Math.sqrt(sumOfSquares);
    if (l2Norm > 0) {
        Object.keys(tfidfVector).forEach(idx => {
            tfidfVector[idx] /= l2Norm;
        });
    }

    let spamProb = 0.0;
    const modelType = MODEL_DATA.model_type;
    const wordContributions = []; // Track per-word spam contribution

    if (modelType === "Logistic Regression") {
        let logOdds = MODEL_DATA.intercept;
        Object.keys(wordToIdx).forEach(word => {
            const idx = wordToIdx[word];
            if (MODEL_DATA.coefficients[idx] !== undefined) {
                const contribution = tfidfVector[idx] * MODEL_DATA.coefficients[idx];
                logOdds += contribution;
                wordContributions.push({ word: word, score: contribution });
            }
        });
        spamProb = 1 / (1 + Math.exp(-logOdds));
        
    } else if (modelType === "Multinomial Naive Bayes") {
        let logLikelihoodHam = MODEL_DATA.class_log_prior[0];
        let logLikelihoodSpam = MODEL_DATA.class_log_prior[1];

        Object.keys(wordToIdx).forEach(word => {
            const idx = wordToIdx[word];
            const tfidfWeight = tfidfVector[idx];
            const spamLogProb = tfidfWeight * MODEL_DATA.feature_log_prob[1][idx];
            const hamLogProb = tfidfWeight * MODEL_DATA.feature_log_prob[0][idx];
            logLikelihoodHam += hamLogProb;
            logLikelihoodSpam += spamLogProb;
            // Contribution = how much more this word points to Spam vs Ham
            wordContributions.push({ word: word, score: spamLogProb - hamLogProb });
        });

        const maxLog = Math.max(logLikelihoodHam, logLikelihoodSpam);
        const expHam = Math.exp(logLikelihoodHam - maxLog);
        const expSpam = Math.exp(logLikelihoodSpam - maxLog);
        spamProb = expSpam / (expHam + expSpam);
    }

    const label = spamProb >= 0.5 ? "Spam" : "Ham";
    const confidence = label === "Spam" ? spamProb : (1 - spamProb);

    // Sort contributions: most positive = most spammy, most negative = most hammy
    wordContributions.sort((a, b) => b.score - a.score);

    return {
        label: label,
        confidence: confidence,
        spamProb: spamProb,
        wordContributions: wordContributions
    };
}

/**
 * Renders initial placeholder charts using dataset-level statistics.
 * These will be replaced by dynamic per-message charts on the first prediction.
 */
function renderInitialCharts() {
    // 1. Initial Pie Chart: Dataset distribution
    const spamDist = MODEL_DATA.spam_distribution;
    const hamCount = spamDist["0"] || 4825;
    const spamCount = spamDist["1"] || 747;
    const totalCount = hamCount + spamCount;

    const ctxDist = document.getElementById("distributionChart").getContext("2d");
    distributionChart = new Chart(ctxDist, {
        type: 'doughnut',
        data: {
            labels: ['Ham (Legitimate)', 'Spam'],
            datasets: [{
                data: [hamCount, spamCount],
                backgroundColor: ['#22c55e', '#ef4444'],
                borderWidth: 2,
                borderColor: '#ffffff'
            }]
        },
        options: {
            responsive: true,
            maintainAspectRatio: false,
            cutout: '55%',
            plugins: {
                legend: {
                    position: 'bottom',
                    labels: { font: { family: 'Inter', size: 12 } }
                },
                tooltip: {
                    callbacks: {
                        label: function(context) {
                            const val = context.raw;
                            const pct = ((val / totalCount) * 100).toFixed(1);
                            return ` ${context.label}: ${val} (${pct}%)`;
                        }
                    }
                }
            }
        }
    });

    // 2. Initial Spam Keywords (from training data)
    const spamKeywords = MODEL_DATA.spam_keywords;
    const spamLabels = spamKeywords.map(k => k[0]);
    const spamScores = spamKeywords.map(k => k[1]);

    const ctxSpam = document.getElementById("spamKeywordsChart").getContext("2d");
    spamKeywordsChart = new Chart(ctxSpam, {
        type: 'bar',
        data: {
            labels: spamLabels,
            datasets: [{
                label: 'Spam Contribution Score',
                data: spamScores,
                backgroundColor: '#ef4444',
                borderRadius: 4
            }]
        },
        options: barChartOptions()
    });

    // 3. Initial Ham Keywords (from training data)
    const hamKeywords = MODEL_DATA.ham_keywords;
    const hamLabels = hamKeywords.map(k => k[0]);
    const hamScores = hamKeywords.map(k => Math.abs(k[1]));

    const ctxHam = document.getElementById("hamKeywordsChart").getContext("2d");
    hamKeywordsChart = new Chart(ctxHam, {
        type: 'bar',
        data: {
            labels: hamLabels,
            datasets: [{
                label: 'Ham Contribution Score',
                data: hamScores,
                backgroundColor: '#22c55e',
                borderRadius: 4
            }]
        },
        options: barChartOptions()
    });
}

/**
 * Destroys and recreates all charts based on the current message's prediction results.
 */
function updateChartsForMessage(prediction) {
    const spamProbPct = prediction.spamProb * 100;
    const hamProbPct = (1 - prediction.spamProb) * 100;

    // ---- 1. Update Pie Chart: Current message's Spam vs Ham probability ----
    if (distributionChart) distributionChart.destroy();

    const ctxDist = document.getElementById("distributionChart").getContext("2d");
    distributionChart = new Chart(ctxDist, {
        type: 'doughnut',
        data: {
            labels: ['Ham Probability', 'Spam Probability'],
            datasets: [{
                data: [hamProbPct.toFixed(2), spamProbPct.toFixed(2)],
                backgroundColor: ['#22c55e', '#ef4444'],
                borderWidth: 3,
                borderColor: '#ffffff'
            }]
        },
        options: {
            responsive: true,
            maintainAspectRatio: false,
            cutout: '55%',
            animation: {
                animateRotate: true,
                duration: 800
            },
            plugins: {
                legend: {
                    position: 'bottom',
                    labels: { font: { family: 'Inter', size: 12, weight: 'bold' } }
                },
                tooltip: {
                    callbacks: {
                        label: function(context) {
                            return ` ${context.label}: ${context.raw}%`;
                        }
                    }
                }
            }
        }
    });

    // ---- 2. Update Keyword Charts: Words from the current message ----
    const contributions = prediction.wordContributions;

    // Separate words pushing toward Spam (positive score) and Ham (negative score)
    const spamWords = contributions.filter(w => w.score > 0).slice(0, 10);
    const hamWords = contributions.filter(w => w.score < 0).slice(-10).reverse();

    // If no words found in a category, show a "no matching words" message
    // Spam keywords chart
    if (spamKeywordsChart) spamKeywordsChart.destroy();
    const ctxSpam = document.getElementById("spamKeywordsChart").getContext("2d");

    if (spamWords.length > 0) {
        spamKeywordsChart = new Chart(ctxSpam, {
            type: 'bar',
            data: {
                labels: spamWords.map(w => w.word),
                datasets: [{
                    label: 'Spam Push Score',
                    data: spamWords.map(w => w.score.toFixed(4)),
                    backgroundColor: spamWords.map((_, i) => {
                        const opacity = 1 - (i * 0.07);
                        return `rgba(239, 68, 68, ${opacity})`;
                    }),
                    borderRadius: 4
                }]
            },
            options: barChartOptions()
        });
    } else {
        spamKeywordsChart = new Chart(ctxSpam, {
            type: 'bar',
            data: {
                labels: ['(No spam-pushing words found)'],
                datasets: [{ data: [0], backgroundColor: '#f1f5f9', borderRadius: 4 }]
            },
            options: barChartOptions()
        });
    }

    // Ham keywords chart
    if (hamKeywordsChart) hamKeywordsChart.destroy();
    const ctxHam = document.getElementById("hamKeywordsChart").getContext("2d");

    if (hamWords.length > 0) {
        hamKeywordsChart = new Chart(ctxHam, {
            type: 'bar',
            data: {
                labels: hamWords.map(w => w.word),
                datasets: [{
                    label: 'Ham Push Score',
                    data: hamWords.map(w => Math.abs(w.score).toFixed(4)),
                    backgroundColor: hamWords.map((_, i) => {
                        const opacity = 1 - (i * 0.07);
                        return `rgba(34, 197, 94, ${opacity})`;
                    }),
                    borderRadius: 4
                }]
            },
            options: barChartOptions()
        });
    } else {
        hamKeywordsChart = new Chart(ctxHam, {
            type: 'bar',
            data: {
                labels: ['(No ham-pushing words found)'],
                datasets: [{ data: [0], backgroundColor: '#f1f5f9', borderRadius: 4 }]
            },
            options: barChartOptions()
        });
    }
}

/**
 * Shared Chart.js options for horizontal bar charts.
 */
function barChartOptions() {
    return {
        indexAxis: 'y',
        responsive: true,
        maintainAspectRatio: false,
        animation: { duration: 600 },
        plugins: {
            legend: { display: false }
        },
        scales: {
            x: {
                grid: { color: '#f1f5f9' },
                ticks: { font: { family: 'Inter', size: 10 } }
            },
            y: {
                grid: { display: false },
                ticks: { font: { family: 'Inter', size: 11, weight: 'bold' } }
            }
        }
    };
}
